import { initWasm, Resvg } from '@resvg/resvg-wasm';
import {
  checkExportAbort,
  exportAssetLimits,
  ownExportAsset,
  type ExportAsset,
} from '@editor-platform/export-core';
import { ownedOfficeFonts, type OfficeFonts } from './fonts';
let initializing: Promise<void> | undefined;

/** Same pinned SVG renderer and font binaries in Node and browser workers; never fetches. */
export async function createOfficeSvgRenderer(wasm: Uint8Array, fonts: OfficeFonts) {
  initializing ??= initWasm(new Uint8Array(wasm)).catch((error: unknown) => {
    initializing = undefined;
    throw error;
  });
  await initializing;
  const buffers = ownedOfficeFonts(fonts);
  const render = (
    svg: string,
    width: number,
    height: number,
    signal?: AbortSignal,
  ): ExportAsset => {
    checkExportAbort(signal);
    if (
      !Number.isSafeInteger(width) ||
      !Number.isSafeInteger(height) ||
      width < 1 ||
      height < 1 ||
      width * height > exportAssetLimits.decodedPixels
    )
      throw Error('Raster limit exceeded');
    // The SVG is generated by a domain renderer. Refuse any unresolved external resources.
    const renderer = new Resvg(svg, {
      dpi: 96,
      font: {
        fontBuffers: buffers,
        defaultFontFamily: fonts.profile.family,
        sansSerifFamily: fonts.profile.family,
      },
      languages: ['ja', 'en'],
    });
    try {
      if (renderer.imagesToResolve().length) throw Error('Raster assets must be embedded');
      const image = renderer.render();
      try {
        if (image.width !== width || image.height !== height)
          throw Error('Raster dimensions changed');
        const asset = ownExportAsset({ bytes: image.asPng(), mime: 'image/png', width, height });
        checkExportAbort(signal);
        return asset;
      } finally {
        image.free();
      }
    } finally {
      renderer.free();
    }
  };
  return Object.assign(render, {
    measure(svg: string) {
      const renderer = new Resvg(svg, {
        dpi: 96,
        font: {
          fontBuffers: buffers,
          defaultFontFamily: fonts.profile.family,
          sansSerifFamily: fonts.profile.family,
        },
        languages: ['ja', 'en'],
      });
      try {
        if (renderer.imagesToResolve().length) throw Error('Raster assets must be embedded');
        const bounds = renderer.getBBox();
        if (!bounds) return;
        try {
          return { x: bounds.x, y: bounds.y, width: bounds.width, height: bounds.height };
        } finally {
          bounds.free();
        }
      } finally {
        renderer.free();
      }
    },
  });
}
