// Writes packages/geometry-cfd/src/d3q27-kernel.generated.ts: the regularised BGK collision of one
// D3Q27 cell, unrolled (VS2, docs/cad/vehicle-simulation.md), and the same collision in WGSL for
// the WebGPU flow (VS2b-3, d3q27-wgsl.generated.ts). Run: node scripts/cfd/generate-d3q27-kernel.mjs,
// then prettier on both files
import { writeFileSync } from 'node:fs';
import { URL } from 'node:url';

const dirs = [];
for (let z = -1; z <= 1; z++)
  for (let y = -1; y <= 1; y++) for (let x = -1; x <= 1; x++) dirs.push([x, y, z]);
const w = ([x, y, z]) => {
  const n = Math.abs(x) + Math.abs(y) + Math.abs(z);
  return n === 0 ? '8 / 27' : n === 1 ? '2 / 27' : n === 2 ? '1 / 54' : '1 / 216';
};
const term = (coef, name) =>
  coef === 0
    ? ''
    : coef > 0
      ? ` + ${coef === 1 ? '' : coef + ' * '}${name}`
      : ` - ${coef === -1 ? '' : -coef + ' * '}${name}`;
const sum = (fn) => {
  let s = '';
  dirs.forEach((d, i) => (s += term(fn(d), `f${i}`)));
  s = s.trim();
  if (s.startsWith('+ ')) s = s.slice(2);
  else if (s.startsWith('- ')) s = '-' + s.slice(2);
  return s || '0';
};
const L = [];
L.push('// Generated by scripts/cfd/generate-d3q27-kernel.mjs. Do not edit.');
L.push('/**');
L.push(
  ' * Collides the cell at `base` (27 values from f, written to post): regularised BGK with relaxation time',
);
L.push(
  ' * tau0 and a Smagorinsky eddy viscosity (cs = 18 √2 C²; 0 = none). Returns u² of the cell.',
);
L.push(' */');
L.push(
  'export function collideD3Q27(f: Float32Array, post: Float32Array, base: number, tau0: number, cs: number): number {',
);
dirs.forEach((_, i) => L.push(`  const f${i} = f[base + ${i}]!;`));
L.push(`  const rho = ${sum(() => 1)};`);
L.push(`  const ux = (${sum((d) => d[0])}) / rho;`);
L.push(`  const uy = (${sum((d) => d[1])}) / rho;`);
L.push(`  const uz = (${sum((d) => d[2])}) / rho;`);
L.push('  const u2 = ux * ux + uy * uy + uz * uz;');
L.push(`  const nxx = ${sum((d) => d[0] * d[0])} - rho * (1 / 3 + ux * ux);`);
L.push(`  const nyy = ${sum((d) => d[1] * d[1])} - rho * (1 / 3 + uy * uy);`);
L.push(`  const nzz = ${sum((d) => d[2] * d[2])} - rho * (1 / 3 + uz * uz);`);
L.push(`  const nxy = ${sum((d) => d[0] * d[1])} - rho * ux * uy;`);
L.push(`  const nxz = ${sum((d) => d[0] * d[2])} - rho * ux * uz;`);
L.push(`  const nyz = ${sum((d) => d[1] * d[2])} - rho * uy * uz;`);
L.push('  let tau = tau0;');
L.push('  if (cs > 0) {');
L.push(
  '    const qn = Math.sqrt(nxx * nxx + nyy * nyy + nzz * nzz + 2 * (nxy * nxy + nxz * nxz + nyz * nyz));',
);
L.push('    tau = 0.5 * (tau0 + Math.sqrt(tau0 * tau0 + (cs * qn) / rho));');
L.push('  }');
L.push('  const k = (1 - 1 / tau) * 4.5;');
L.push('  const r0 = rho * (1 - 1.5 * u2);');
L.push('  const t0 = -k * (1 / 3) * (nxx + nyy + nzz);');
dirs.forEach(([x, y, z], i) => {
  const cu =
    [term(x, 'ux'), term(y, 'uy'), term(z, 'uz')]
      .join('')
      .trim()
      .replace(/^\+ /, '')
      .replace(/^- /, '-') || '0';
  // Q_i : Π for this direction: diagonal part (c_a² − 1/3) Π_aa, off-diagonal 2 c_a c_b Π_ab.
  let diag;
  const ax = x !== 0,
    ay = y !== 0,
    az = z !== 0;
  // (x²−⅓)nxx + (y²−⅓)nyy + (z²−⅓)nzz, written from the precomputed pieces.
  diag = `${ax ? 'k * nxx' : '0'} + ${ay ? 'k * nyy' : '0'} + ${az ? 'k * nzz' : '0'} + t0`;
  let off = '';
  if (x * y) off += ` ${x * y > 0 ? '+' : '-'} 2 * k * nxy`;
  if (x * z) off += ` ${x * z > 0 ? '+' : '-'} 2 * k * nxz`;
  if (y * z) off += ` ${y * z > 0 ? '+' : '-'} 2 * k * nyz`;
  L.push(
    `  { const cu = ${cu}; post[base + ${i}] = (${w([x, y, z])}) * (r0 + rho * (3 * cu + 4.5 * cu * cu) + ${diag}${off}); }`,
  );
});
L.push('  return u2;');
L.push('}');
L.push('');
writeFileSync(
  new URL('../../packages/geometry-cfd/src/d3q27-kernel.generated.ts', import.meta.url),
  L.join('\n'),
);

// The same collision in WGSL: `fin` and `post` are the storage arrays of the WebGPU flow; every
// literal is written as a float (an integer division in WGSL would truncate).
const fl = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const wsum = (fn) => {
  let s = '';
  dirs.forEach((d, i) => {
    const c = fn(d);
    if (c === 0) return;
    s +=
      c > 0
        ? ` + ${c === 1 ? '' : fl(c) + ' * '}f${i}`
        : ` - ${c === -1 ? '' : fl(-c) + ' * '}f${i}`;
  });
  s = s.trim();
  if (s.startsWith('+ ')) s = s.slice(2);
  else if (s.startsWith('- ')) s = '-' + s.slice(2);
  return s || '0.0';
};
const ww = ([x, y, z]) => {
  const n = Math.abs(x) + Math.abs(y) + Math.abs(z);
  return n === 0
    ? '(8.0 / 27.0)'
    : n === 1
      ? '(2.0 / 27.0)'
      : n === 2
        ? '(1.0 / 54.0)'
        : '(1.0 / 216.0)';
};
const G = [];
G.push('fn collide(base: u32, tau0: f32, cs: f32) -> f32 {');
dirs.forEach((_, i) => G.push(`  let f${i} = fin[base + ${i}u];`));
G.push(`  let rho = ${wsum(() => 1)};`);
G.push(`  let ux = (${wsum((d) => d[0])}) / rho;`);
G.push(`  let uy = (${wsum((d) => d[1])}) / rho;`);
G.push(`  let uz = (${wsum((d) => d[2])}) / rho;`);
G.push('  let u2 = ux * ux + uy * uy + uz * uz;');
G.push(`  let nxx = ${wsum((d) => d[0] * d[0])} - rho * (1.0 / 3.0 + ux * ux);`);
G.push(`  let nyy = ${wsum((d) => d[1] * d[1])} - rho * (1.0 / 3.0 + uy * uy);`);
G.push(`  let nzz = ${wsum((d) => d[2] * d[2])} - rho * (1.0 / 3.0 + uz * uz);`);
G.push(`  let nxy = ${wsum((d) => d[0] * d[1])} - rho * ux * uy;`);
G.push(`  let nxz = ${wsum((d) => d[0] * d[2])} - rho * ux * uz;`);
G.push(`  let nyz = ${wsum((d) => d[1] * d[2])} - rho * uy * uz;`);
G.push('  var tau = tau0;');
G.push('  if (cs > 0.0) {');
G.push(
  '    let qn = sqrt(nxx * nxx + nyy * nyy + nzz * nzz + 2.0 * (nxy * nxy + nxz * nxz + nyz * nyz));',
);
G.push('    tau = 0.5 * (tau0 + sqrt(tau0 * tau0 + (cs * qn) / rho));');
G.push('  }');
G.push('  let k = (1.0 - 1.0 / tau) * 4.5;');
G.push('  let r0 = rho * (1.0 - 1.5 * u2);');
G.push('  let t0 = -k * (1.0 / 3.0) * (nxx + nyy + nzz);');
dirs.forEach(([x, y, z], i) => {
  let cu = '';
  for (const [c, n] of [
    [x, 'ux'],
    [y, 'uy'],
    [z, 'uz'],
  ])
    if (c) cu += c > 0 ? ` + ${n}` : ` - ${n}`;
  cu = cu.trim().replace(/^\+ /, '').replace(/^- /, '-') || '0.0';
  const diag = `${x ? 'k * nxx' : '0.0'} + ${y ? 'k * nyy' : '0.0'} + ${z ? 'k * nzz' : '0.0'} + t0`;
  let off = '';
  if (x * y) off += ` ${x * y > 0 ? '+' : '-'} 2.0 * k * nxy`;
  if (x * z) off += ` ${x * z > 0 ? '+' : '-'} 2.0 * k * nxz`;
  if (y * z) off += ` ${y * z > 0 ? '+' : '-'} 2.0 * k * nyz`;
  G.push(
    `  { let cu = ${cu}; post[base + ${i}u] = ${ww([x, y, z])} * (r0 + rho * (3.0 * cu + 4.5 * cu * cu) + ${diag}${off}); }`,
  );
});
G.push('  return u2;');
G.push('}');
writeFileSync(
  new URL('../../packages/geometry-cfd/src/d3q27-wgsl.generated.ts', import.meta.url),
  [
    '// Generated by scripts/cfd/generate-d3q27-kernel.mjs. Do not edit.',
    '/** The D3Q27 collision of `collideD3Q27` in WGSL (reads `fin`, writes `post`, returns u²). */',
    `export const collideD3Q27Wgsl = ${JSON.stringify(G.join('\n') + '\n')};`,
    '',
  ].join('\n'),
);
