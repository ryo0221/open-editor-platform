/** Trusted Host build only: compile a closed Counter graph and pin all admitted bytes. */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';
import type * as Sample from '@editor-platform/extension-sample';
import type * as Bundles from './src/bundled-package';
export async function buildCounterPackages() {
  // Vite config externalizes workspace TS packages. Bundle trusted build helpers as well,
  // so Node never has to resolve their extensionless TypeScript imports.
  const helpers = await build({
    stdin: {
      contents: `export { counterExtension } from '@editor-platform/extension-sample';
export { describeBundledPackage } from './src/bundled-package';`,
      resolveDir: fileURLToPath(new URL('.', import.meta.url)),
    },
    bundle: true,
    write: false,
    platform: 'node',
    format: 'esm',
  });
  const { counterExtension, describeBundledPackage }: typeof Sample & typeof Bundles = await import(
    `data:text/javascript;base64,${Buffer.from(helpers.outputFiles![0].contents).toString('base64')}`
  );
  const packages = [];
  for (const version of ['0.0.1', '0.0.2'] as const) {
    const built = await build({
      stdin: {
        contents: `import { counterExtension } from '@editor-platform/extension-sample';
export function definition(hash) { const d = counterExtension(hash); d.manifest.version = ${JSON.stringify(version)}; return d; }`,
        resolveDir: fileURLToPath(new URL('.', import.meta.url)),
      },
      bundle: true,
      write: false,
      platform: 'browser',
      format: 'esm',
      metafile: true,
      legalComments: 'inline',
    });
    if (Object.values(built.metafile!.outputs).some((output) => output.imports.length))
      throw Error('Counter bundle must have no external imports');
    const { packageHash: _ignored, ...manifest } = counterExtension(
      `sha256:${'0'.repeat(64)}`,
    ).manifest;
    manifest.version = version;
    const prepared = await describeBundledPackage({
      manifest,
      entry: 'counter.js',
      files: [{ path: 'counter.js', bytes: built.outputFiles![0].contents }],
    });
    packages.push({
      manifest,
      entry: 'counter.js',
      hash: prepared.hash,
      files: prepared.files.map((file) => ({
        path: file.path,
        text: new TextDecoder('utf-8', { fatal: true }).decode(file.bytes),
      })),
    });
  }
  return packages;
}
export function bundledCounterPlugin(): Plugin {
  const name = 'virtual:bundled-counter';
  return {
    name: 'host-bundled-counter',
    resolveId(id) {
      if (id === name) return `\0${name}`;
    },
    async load(id) {
      if (id !== `\0${name}`) return;
      const packages = await buildCounterPackages();
      // These pins are generated by the trusted Host build, never accepted from a downloaded package.
      return `export const pins = ${JSON.stringify(Object.fromEntries(packages.map((p) => [p.manifest.version, p.hash])))};
export const packages = ${JSON.stringify(packages.map(({ hash: _hash, ...p }) => p))};`;
    },
  };
}
